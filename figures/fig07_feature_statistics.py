def apply_figure_style(*, frame="open", font=None, sizes=(8, 7, 6), grid=False):
    import matplotlib as mpl
    if frame not in ("open", "boxed", "none"):
        raise ValueError(f"frame must be 'open'|'boxed'|'none', got {frame!r}")
    try:
        import os, sys, glob, matplotlib.font_manager as fm
        fdir = os.path.join(os.environ.get("CONDA_PREFIX") or sys.prefix, "fonts")
        if os.path.isdir(fdir):
            known = {f.fname for f in fm.fontManager.ttflist}
            for f in glob.glob(os.path.join(fdir, "*.ttf")):
                if f not in known:
                    fm.fontManager.addfont(f)
    except Exception:
        pass
    base, secondary, tick = sizes
    boxed = (frame == "boxed")
    rc = {
        "font.family": "sans-serif",
        "font.size": base,
        "axes.labelsize": base,
        "axes.titlesize": base,
        "legend.fontsize": secondary,
        "xtick.labelsize": tick,
        "ytick.labelsize": tick,
        "axes.linewidth": 0.6,
        "xtick.direction": "out", "ytick.direction": "out",
        "xtick.major.size": 3, "ytick.major.size": 3,
        "xtick.major.width": 0.6, "ytick.major.width": 0.6,
        "axes.spines.top": boxed, "axes.spines.right": boxed,
        "axes.spines.left": frame != "none", "axes.spines.bottom": frame != "none",
        "axes.grid": bool(grid),
        "legend.frameon": False,
        "figure.dpi": 200,
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
        "axes.titleweight": "normal",
        "axes.titlelocation": "left",
        "axes.labelweight": "normal",
        "lines.linewidth": 1.2,
        "patch.linewidth": 0.6,
        "pdf.fonttype": 42, "ps.fonttype": 42,
    }
    if font:
        rc["font.sans-serif"] = [font, "DejaVu Sans"]
    mpl.rcParams.update(rc)


from repro.figstyle import panel_letter   # UPPERCASE BOLD SERIF, manuscript convention


def fig_statistics():
    top = pd.read_csv(RPATH("top10_features.csv"))
    bc = pd.read_csv(RPATH("bit_collision_prevalence.csv")).set_index("bit")
    apply_figure_style(sizes=(8, 7, 6))
    fig = plt.figure(figsize=(7.2, 7.4))
    gs = fig.add_gridspec(2, 2, height_ratios=[1.32, 1.0], hspace=0.44, wspace=0.44)

    ax = fig.add_subplot(gs[0, :])
    M = np.array([[top[f"mean_abs_shap_{t}"].iloc[i] for t in TASKS] for i in range(10)]) * 1e3
    im = ax.imshow(M, cmap="viridis", aspect="auto")
    ax.set_xticks(range(6)); ax.set_xticklabels(TASKS)
    ax.set_yticks(range(10))
    ax.set_yticklabels([f"{i+1}. {SHORT[f]}" for i, f in enumerate(top['feature'])])
    for i in range(10):
        for j in range(6):
            ax.text(j, i, f"{M[i, j]:.1f}", ha="center", va="center", fontsize=5.6,
                    color="white" if M[i, j] < M.max() * 0.55 else "black")
    for i, f in enumerate(top["feature"]):
        ax.get_yticklabels()[i].set_color(BIT_C if f.startswith("ECFP4") else DESC_C)
    cb = fig.colorbar(im, ax=ax, fraction=0.022, pad=0.015)
    cb.set_label("mean |SHAP| ($\\times10^{-3}$)", fontsize=6)
    cb.ax.tick_params(labelsize=5.5)
    ax.set_title("Each substructure bit drives one target; the descriptors drive all six",
                 loc="left", pad=4)
    panel_letter(ax, "a", dx=-0.13, dy=1.06)

    ax = fig.add_subplot(gs[1, 0])
    y = np.arange(10)[::-1]
    es = top["effect_size"].to_numpy()
    lab = [f"{i+1}. {SHORT[f]}" for i, f in enumerate(top["feature"])]
    isbit = top["feature"].str.startswith("ECFP4").to_numpy()
    val = np.where(isbit, np.log2(np.where(isbit, es, 1.0)), es)
    cols = [BIT_C if b else DESC_C for b in isbit]
    ax.axvline(0, color=META_GREY, lw=0.7)
    ax.hlines(y, 0, val, color=cols, lw=1.1)
    ax.scatter(val, y, c=cols, s=22, zorder=3)
    ax.set_yticks(y); ax.set_yticklabels(lab, fontsize=6)
    # The unit key moved into the axis label. Now that every lollipop carries its own
    # value, the in-axes note had no free corner left: at the foot of the panel it sat
    # on the bottom row's label and one row up it sat on bit 1535's. The axis label is
    # where a unit belongs anyway.
    ax.set_xlabel("actives vs inactives effect size\n"
                  "(bits: log$_2$ odds ratio; descriptors: Cohen $d$)")
    ax.set_title("Direction and size of the\nactive/inactive separation", loc="left", pad=4)
    # Every lollipop carries its own value. The panel previously showed direction and
    # relative length only, so a reader could not recover the effect size of any one
    # feature from it. The label sits past the marker on the side the bar points, so
    # it never falls on the zero rule.
    for yy, v, cc in zip(y, val, cols):
        off = 6 if v >= 0 else -6
        ax.annotate(f"{v:+.2f}", (v, yy), xytext=(off, 0), textcoords="offset points",
                    va="center", ha="left" if v >= 0 else "right",
                    fontsize=5.4, color=cc)
    # Raised one row: at 0.04 the key sat on the bottom lollipop's new value label.
    # The row above it carries its label on the left, so the right side is clear here.
    ax.margins(y=0.05, x=0.20)
    panel_letter(ax, "b", dx=-0.42, dy=1.06)

    ax = fig.add_subplot(gs[1, 1])
    shift, txt = [], []
    for i, f in enumerate(top["feature"]):
        if f.startswith("ECFP4"):
            b = int(f.split("_")[-1])
            pc = bc.loc[b, "chembl_modal_prevalence"]; pmv = bc.loc[b, "marine_modal_prevalence"]
            shift.append(np.log10(max(pmv, 1e-5) / pc))
            txt.append(f"{pc*100:.1f}% $\\rightarrow$ {pmv*100:.3f}%")
        else:
            # The descriptor rows were left unlabelled, so the orange lollipops showed
            # a displacement with no readable magnitude while the blue ones carried a
            # prevalence transition. They get their own value on the same footing.
            d = -top["marine_vs_chembl_cohens_d"].iloc[i]
            shift.append(d)
            txt.append(f"$d$ = {d:+.2f}")
    ax.axvline(0, color=META_GREY, lw=0.7)
    ax.hlines(y, 0, shift, color=cols, lw=1.1)
    ax.scatter(shift, y, c=cols, s=22, zorder=3)
    for yy, s, tt, cc in zip(y, shift, txt, cols):
        if tt:
            ax.annotate(tt, (s, yy), xytext=(0, 5), textcoords="offset points",
                        fontsize=5.4, va="bottom",
                        ha="left" if s >= 0 else "right", color=cc)
    ax.set_yticks(y); ax.set_yticklabels([])
    ax.set_xlabel("marine library relative to ChEMBL pool\n"
                  "(bits: log$_{10}$ prevalence ratio; descriptors: $-$Cohen $d$)")
    ax.set_title("Displacement of each feature from the\ntraining pool to the marine library",
                 loc="left", pad=4)
    ax.margins(y=0.05, x=0.22)
    panel_letter(ax, "c", dx=-0.10, dy=1.06)

    fig.savefig("fig_top10_feature_statistics.png", dpi=300, bbox_inches="tight")
    fig.savefig("fig_top10_feature_statistics.pdf", bbox_inches="tight")
    print("saved fig_top10_feature_statistics", flush=True)
    return fig


