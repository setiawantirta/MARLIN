# ------------------------------------- effect size + significance on each panel
# Every displayed contrast reaches ** after BH correction across the eight of them,
# because n runs from 126 to 6,445 molecules rather than a handful of models (the
# GNNExplainer row of panel F is a 126-molecule subsample; the rest are 1,164-6,445).
# A bare star
# would therefore print the same symbol on Cohen's d = 1.55 (panel B) and d = -0.17
# (panel D), so the label carries the effect size as well. Panel E is skipped on
# purpose: six cosine similarities with no comparison group admit no test.
# Guarded - a labelling failure must not cost the whole render.
try:
    import repro.siglabels as _SL
    import pandas as _pd
    _gv = _pd.read_csv(RPATH("gnn_vs_rf_attribution.csv"))
    _tt = _SL.attribution_tests(_gv, _SL.FIG5_PANELS)
    _AXBYL = {"A": 0, "B": 1, "C": 2, "D": 3, "F": 5}   # fig.axes order is a..f
    for _pn, _g in _tt.groupby("panel"):
        _ax = _fig.axes[_AXBYL[_pn]]
        _txt = "\n".join(_SL.effect_label(r.cohens_d, r.q_BH) for _, r in _g.iterrows())
        # A bracket spanning the two groups actually compared, in the GraphPad
        # idiom: end ticks on the two x positions, asterisks centred above. The
        # y coordinate is an axes fraction so the bar sits clear of the data
        # whatever the panel's scale, and a second contrast in the same panel is
        # stacked one level higher. Headroom is opened below so the brackets do
        # not collide with the panel above.
        for _, _r in _g.iterrows():
            _x1, _x2, _lvl = _SL.FIG5_BRACKETS[_r.metric]
            _SL.sig_bracket(_ax, _x1, _x2, _r.q_BH, d=_r.cohens_d, level=_lvl)
        _ax.set_ylim(top=_ax.get_ylim()[1] + (_ax.get_ylim()[1] - _ax.get_ylim()[0])
                     * (0.26 if len(_g) > 1 else 0.14))
    print("SIGSTARS", "fig05", len(_tt), "contrasts labelled across",
          _tt.panel.nunique(), "panels (E has no testable contrast)", flush=True)
except Exception as _e:
    print("SIGSTARS_SKIPPED", "fig05", type(_e).__name__, str(_e)[:120], flush=True)

