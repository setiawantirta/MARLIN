def fig_rf_vs_gnn():
    g = pd.read_csv(RPATH("gnn_rf_atom_attrib.csv"))
    gv = pd.read_csv(RPATH("gnn_vs_rf_attribution.csv"))
    svt = {
        "EGFR": np.load(RPATH("shap_test_EGFR.npz"))["sv"],
        "PDGFRA": np.load(RPATH("shap_test_PDGFRA.npz"))["sv"],
        "PIK3CA": np.load(RPATH("shap_test_PIK3CA.npz"))["sv"],
        "KDR": np.load(RPATH("shap_test_KDR.npz"))["sv"],
        "CDK6": np.load(RPATH("shap_test_CDK6.npz"))["sv"],
        "IDH1": np.load(RPATH("shap_test_IDH1.npz"))["sv"],
    }
    svm = {
        "EGFR": np.load(RPATH("shap_marine_EGFR.npz"))["sv"],
        "PDGFRA": np.load(RPATH("shap_marine_PDGFRA.npz"))["sv"],
        "PIK3CA": np.load(RPATH("shap_marine_PIK3CA.npz"))["sv"],
        "KDR": np.load(RPATH("shap_marine_KDR.npz"))["sv"],
        "CDK6": np.load(RPATH("shap_marine_CDK6.npz"))["sv"],
        "IDH1": np.load(RPATH("shap_marine_IDH1.npz"))["sv"],
    }
    apply_figure_style(sizes=(8, 7, 6))
    SYN, MAR = "#4c72a0", "#c1682e"
    # The canvas is 6.25 in rather than 5.8 in, and the grid is given explicit
    # top/bottom, to open two margin bands for legends that previously sat inside the
    # axes and covered data: one above row 1 (RF/D-MPNN key for panels b and c) and one
    # below row 2 (ChEMBL/CMNPD key for panel f). left/right are pinned at the matplotlib
    # defaults that the original figure inherited, and top-bottom is chosen so each panel
    # keeps its previous physical height (0.2554 x 6.25 in = 0.277 x 5.8 in).
    fig = plt.figure(figsize=(7.2, 6.25))
    gs = fig.add_gridspec(2, 3, hspace=0.78, wspace=0.68,
                          left=0.125, right=0.900, top=0.845, bottom=0.135)
    S = g[g["set"] == "synthetic_test"]; M = g[g["set"] == "marine"]

    ax = fig.add_subplot(gs[0, 0])
    for k, (d, c) in enumerate([(S["rf_gnn_atom_rho"].dropna(), SYN),
                                (M["rf_gnn_atom_rho"].dropna(), MAR)]):
        xx = np.random.default_rng(k).normal(k, 0.07, len(d))
        ax.scatter(xx, d, s=3, alpha=0.25, color=c, edgecolors="none")
        ax.hlines(np.median(d), k - 0.26, k + 0.26, color=c, lw=2.2, zorder=4)
        # black glyphs with a thin white halo: drawn in the group colour they were
        # indistinguishable from the scatter cloud underneath (worst for 0.097, which
        # falls in the densest part of the marine distribution)
        ax.annotate(f"{np.median(d):.3f}", (k, np.median(d)), xytext=(0, 13),
                    textcoords="offset points", ha="center", fontsize=6.2, color="black",
                    zorder=6,
                    path_effects=[mpe.withStroke(linewidth=2.5, foreground="white")])
    ax.axhline(0, color=META_GREY, lw=0.7)
    ax.set_xticks([0, 1]); ax.set_xticklabels(["ChEMBL\ntest", "CMNPD\nmarine"])
    ax.set_ylabel("Spearman $\\rho$, RF vs GNN\nper-atom attribution")
    ax.set_title("Model agreement collapses\non marine NPs", loc="left", pad=4)
    ax.margins(y=0.06)
    panel_letter(ax, "a", dx=-0.44, dy=1.10)

    for pi, (col_g, col_r, nm, ttl) in enumerate([
            ("gnn_frac_aromatic", "rf_frac_aromatic", "aromatic atoms",
             "Aromatic share falls\nin marine NPs"),
            ("gnn_frac_sp3", "rf_frac_sp3", "sp$^3$ atoms",
             "sp3 share rises\nin marine NPs")]):
        ax = fig.add_subplot(gs[0, pi + 1])
        pos, vals, colr = [], [], []
        for j, (sub, c) in enumerate([(S, SYN), (M, MAR)]):
            vals += [sub[col_r].dropna(), sub[col_g].dropna()]
            pos += [j * 2.4, j * 2.4 + 0.85]
            colr += [c, c]
        bp = ax.boxplot(vals, positions=pos, widths=0.62, showfliers=False,
                        patch_artist=True, medianprops=dict(color="black", lw=1.0))
        for i, (patch, c) in enumerate(zip(bp["boxes"], colr)):
            patch.set_facecolor(c if i % 2 == 0 else "white")
            patch.set_edgecolor(c); patch.set_linewidth(1.0)
        ax.set_xticks([0.42, 2.82]); ax.set_xticklabels(["ChEMBL\ntest", "CMNPD\nmarine"])
        ax.set_ylabel(f"share of |attribution|\non {nm}")
        ax.set_title(ttl, loc="left", pad=4)
        panel_letter(ax, "bc"[pi], dx=-0.40, dy=1.10)

    # Panels b and c share the filled/open encoding, so one figure-level key above them
    # replaces the two in-axes legends. In panel b the upper-right in-axes legend sat on
    # the ChEMBL-test RF upper whisker cap, which reaches exactly 1.0.
    # Four entries, not two. The previous key named only the fill convention
    # (solid = RF/SHAP, open = D-MPNN/IG) and left the colour unexplained, so a
    # reader could not tell which of the four boxes in each panel was which: the
    # blue pair is the ChEMBL test partition and the orange pair the CMNPD marine
    # library, and each pair carries one box per attribution method. Spelling all
    # four out removes the ambiguity even though the x-axis also groups them.
    fig.legend(handles=[
        mpl.patches.Patch(facecolor=SYN, edgecolor=SYN, label="RF (SHAP), ChEMBL test"),
        mpl.patches.Patch(facecolor="white", edgecolor=SYN, label="D-MPNN (IG), ChEMBL test"),
        mpl.patches.Patch(facecolor=MAR, edgecolor=MAR, label="RF (SHAP), CMNPD marine"),
        mpl.patches.Patch(facecolor="white", edgecolor=MAR, label="D-MPNN (IG), CMNPD marine")],
        loc="center", bbox_to_anchor=(0.662, 0.952), ncol=2,
        frameon=False, fontsize=5.6, handlelength=1.2, columnspacing=1.4,
        labelspacing=0.35)

    ax = fig.add_subplot(gs[1, 0])
    ds = {}
    for lbl, src in [("chembl", svt), ("marine", svm)]:
        v = []
        for t in TASKS:
            A = src[t]; tot = np.abs(A).sum(1)
            v.append(np.where(tot > 0, np.abs(A[:, 2048:]).sum(1) / tot, np.nan))
        ds[lbl] = np.concatenate(v)
    for k, (lbl, c) in enumerate([("chembl", SYN), ("marine", MAR)]):
        d = ds[lbl][np.isfinite(ds[lbl])]
        ax.bar(k, d.mean(), 0.55, color=c, yerr=d.std() / np.sqrt(len(d)), capsize=2)
        ax.annotate(f"{d.mean()*100:.1f}%", (k, d.mean()), xytext=(0, 3),
                    textcoords="offset points", ha="center", fontsize=6.4)
    ax.plot([2], [0.004], marker="_", ms=14, color="#8a8a8a", mew=2.0)
    ax.annotate("0% by\nconstruction", (2, 0.01), xytext=(0, 3), textcoords="offset points",
                ha="center", fontsize=5.8, color=META_GREY)
    ax.set_xticks([0, 1, 2])
    ax.set_xticklabels(["RF\nChEMBL", "RF\nmarine", "D-MPNN\n(any set)"])
    ax.set_ylabel("fraction of |attribution| that is\nnon-local (global descriptors)")
    ax.set_title("Only the RF has a\nnon-local channel", loc="left", pad=4)
    ax.set_ylim(0, 0.45)
    panel_letter(ax, "d", dx=-0.46, dy=1.10)

    ax = fig.add_subplot(gs[1, 1])
    cos = [float(gv[(gv["metric"].str.startswith("IG mean atom-feature")) &
                    (gv["group_a"] == t)]["mean_a"].iloc[0]) for t in TASKS]
    ax.barh(np.arange(6)[::-1], cos, 0.62, color="#7a7a7a")
    for k, c in zip(np.arange(6)[::-1], cos):
        ax.annotate(f"{c:.3f}", (c, k), xytext=(-3, 0), textcoords="offset points",
                    ha="right", va="center", fontsize=6, color="white")
    ax.set_yticks(np.arange(6)[::-1]); ax.set_yticklabels(TASKS)
    ax.set_xlim(0.85, 1.0); ax.set_xlabel("cosine(synthetic, marine)")
    ax.set_title("Unchanged atom-feature\nkey across domains",
                 loc="left", pad=4)
    panel_letter(ax, "e", dx=-0.36, dy=1.10)

    ax = fig.add_subplot(gs[1, 2])
    ge = pd.read_csv(RPATH("gnnexplainer_atom_attrib.csv"))
    grp = [(S["gnn_frac_scaffold"].dropna(), SYN, 0),
           (M["gnn_frac_scaffold"].dropna(), MAR, 0.85),
           (ge[ge["set"] == "synthetic_test"]["gnnexp_frac_scaffold"].dropna(), SYN, 2.4),
           (ge[ge["set"] == "marine"]["gnnexp_frac_scaffold"].dropna(), MAR, 3.25)]
    for d, c, p in grp:
        ax.bar(p, d.mean(), 0.66, color=c, yerr=d.std() / np.sqrt(len(d)), capsize=2)
    ax.set_xticks([0.42, 2.82]); ax.set_xticklabels(["Integrated\ngradients", "GNN-\nExplainer"])
    ax.set_ylabel("share of atom attribution\non scaffold atoms")
    ax.set_title("Scaffold-centred under\nboth graph methods",
                 loc="left", pad=4)
    ax.set_ylim(0, 1.0)
    # Bars start at zero, so the lower-right corner this legend used to occupy was
    # covered data (the y 0.1-0.25 band of both GNN-Explainer bars); with the tallest bar
    # at 0.84 no in-axes corner is free on both sides, so the key goes below the axes.
    ax.legend(handles=[mpl.patches.Patch(color=SYN, label="ChEMBL test"),
                       mpl.patches.Patch(color=MAR, label="CMNPD marine")],
              loc="upper center", bbox_to_anchor=(0.5, -0.26), ncol=2,
              frameon=False, fontsize=5.8, handlelength=1.2, columnspacing=1.4)
    panel_letter(ax, "f", dx=-0.40, dy=1.10)

    fig.savefig("fig_rf_vs_gnn_attribution.png", dpi=300, bbox_inches="tight")
    fig.savefig("fig_rf_vs_gnn_attribution.pdf", bbox_inches="tight")
    print("saved fig_rf_vs_gnn_attribution", flush=True)
    return fig


