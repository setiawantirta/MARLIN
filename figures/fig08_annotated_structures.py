def bit_hits(mol, bit):
    ao = rdFingerprintGenerator.AdditionalOutput()
    ao.AllocateBitInfoMap()
    FP_GEN.GetFingerprint(mol, additionalOutput=ao)
    atoms, bonds = set(), set()
    for (centre, rad) in ao.GetBitInfoMap().get(bit, ()):
        if rad == 0:
            atoms.add(centre)
            continue
        bl = list(Chem.FindAtomEnvironmentOfRadiusN(mol, rad, centre))
        amap = {}
        Chem.PathToSubmol(mol, bl, atomMap=amap)
        atoms |= set(amap.keys()) if amap else {centre}
        bonds |= set(bl)
    return sorted(atoms), sorted(bonds)


def highlight_for(feature, mol):
    if feature.startswith("ECFP4_bit_"):
        return bit_hits(mol, int(feature.split("_")[-1]))
    if feature == "MolLogP":
        # The Wildman-Crippen decomposition is exact only with explicit hydrogens: summed
        # over heavy atoms alone it recovers ~40-55% of MolLogP, whereas summed over an
        # H-added molecule it reproduces Crippen.MolLogP to 1e-6. Each hydrogen's
        # contribution is therefore folded into its parent heavy atom, so the per-atom
        # values drawn here sum exactly to the molecule's MolLogP.
        mh = Chem.AddHs(mol)
        ch = [a for a, _ in rdMolDescriptors._CalcCrippenContribs(mh)]
        n = mol.GetNumAtoms()
        c = np.zeros(n)
        for i, a in enumerate(mh.GetAtoms()):
            if i < n:
                c[i] += ch[i]
            else:
                c[a.GetNeighbors()[0].GetIdx()] += ch[i]
        assert abs(c.sum() - Crippen.MolLogP(mol)) < 1e-6, (c.sum(), Crippen.MolLogP(mol))
        pos = np.where(c > 0)[0]
        if len(pos) == 0:
            return [], []
        thr = np.quantile(c[pos], 0.75)
        at = sorted(int(i) for i in pos if c[i] >= thr)
        bo = [b.GetIdx() for b in mol.GetBonds()
              if b.GetBeginAtomIdx() in at and b.GetEndAtomIdx() in at]
        return at, bo
    if feature == "NumHAcceptors":
        at = sorted({i for m in mol.GetSubstructMatches(Lipinski.HAcceptorSmarts) for i in m})
        return at, []
    return [], []


def draw(mol, atoms, bonds, colour, px=(1050, 620)):
    d = rdMolDraw2D.MolDraw2DCairo(*px)
    o = d.drawOptions()
    o.addStereoAnnotation = False
    o.bondLineWidth = 2
    o.highlightBondWidthMultiplier = 14
    o.fixedFontSize = 21
    o.minFontSize = 15
    rdMolDraw2D.PrepareAndDrawMolecule(
        d, mol, highlightAtoms=atoms, highlightBonds=bonds,
        highlightAtomColors={a: colour for a in atoms},
        highlightBondColors={b: colour for b in bonds})
    d.FinishDrawing()
    return Image.open(io.BytesIO(d.GetDrawingText()))


def main():
    ex = json.load(open(RPATH("fig_exemplars.json")))
    top = pd.read_csv(RPATH("top10_features.csv"))
    cr = np.load(RPATH("cmnpd_raw.npz"))
    raw = np.load(RPATH("chembl_raw.npz"))
    Dm, Dc, Y, mask, okc = cr["D"], raw["D"], raw["Y"], raw["mask"], raw["ok"]
    DESCN = list(np.load(RPATH("featnames.npy")))[2048:]

    apply_figure_style(sizes=(8, 7, 6))
    LOCAL = "#1f6f8b"        # atoms/bonds carrying an atom-resolved feature
    rgb_local = mpl.colors.to_rgb(LOCAL)

    fig, axes = plt.subplots(5, 2, figsize=(7.2, 10.6))
    order = list(top["feature"])
    global_panels = []
    for k, feat in enumerate(order):
        ax = axes[k // 2, k % 2]
        ax.set_axis_off()
        d = ex[feat]
        mol = Chem.MolFromSmiles(d["smiles"])
        at, bo = highlight_for(feat, mol)
        img = draw(mol, at, bo, rgb_local)
        ax.imshow(np.asarray(img), interpolation="lanczos")
        panel_letter(ax, "abcdefghij"[k], dx=-0.03, dy=1.13)
        label = TRIVIAL.get(d["cmnpd_id"], d["cmnpd_id"])
        if d["cmnpd_id"] in TRIVIAL:
            label = f"{label} ({d['cmnpd_id']})"
        r = top[top["feature"] == feat].iloc[0]
        head = f"{d['rank']}. {PRETTY[feat]}"
        sub = (f"{label}  |  SHAP {d['shap_contrib']:+.3f} $\\rightarrow$ {d['target']}")
        if not at:
            global_panels.append("abcdefghij"[k])
            di = DESCN.index(feat)
            v = float(Dm[d["row"], di])
            pm = float((Dm[:, di] <= v).mean() * 100)
            av = np.concatenate([Dc[(mask[:, ti] > 0) & okc & (Y[:, ti] > 0.5), di]
                                 for ti in range(len(TASKS))])
            pa = float((av <= v).mean() * 100)
            sub += (f"\nvalue {v:.3g}  -  percentile {pm:.0f} in marine library, "
                    f"{pa:.0f} in ChEMBL actives")
        else:
            sub += f"\n{len(at)} contributing atoms highlighted"
        ax.set_title(head, fontsize=8, loc="left", pad=3)
        ax.text(0.0, -0.055, sub, transform=ax.transAxes, fontsize=6.4, va="top", ha="left")

    fig.text(0.5, 0.008,
             "Highlighted atoms carry the feature. Whole-graph indices (panels "
             + ", ".join(global_panels) +
             ") have no atom locus and are drawn unhighlighted.",
             ha="center", fontsize=6.2, color=META_GREY)
    fig.tight_layout(rect=(0, 0.022, 1, 1))
    fig.subplots_adjust(hspace=0.60)
    fig.savefig("fig_top10_annotated_structures.png", dpi=300)
    fig.savefig("fig_top10_annotated_structures.pdf")
    print("saved fig_top10_annotated_structures", flush=True)
    return fig


