def cclass(m, row):
    if m is None: return 'unparsed'
    hal = any(a.GetSymbol() in ('Br','Cl','I','F') for a in m.GetAtoms())
    nN = sum(a.GetSymbol()=='N' for a in m.GetAtoms())
    nO = sum(a.GetSymbol()=='O' for a in m.GetAtoms())
    nS = sum(a.GetSymbol()=='S' for a in m.GetAtoms())
    if row['peptide_like'] or row['n_amide_bonds']>=4: base='peptide'
    elif m.HasSubstructMatch(patt['steroid']): base='steroid/sterol'
    elif nN>=1 and (m.HasSubstructMatch(patt['basic_N_ring']) or m.HasSubstructMatch(patt['aromatic_N_ring'])): base='alkaloid'
    elif nN==0 and row['fraction_csp3']>=0.7 and row['n_rings']>=2: base='terpenoid'
    elif nN==0 and (m.HasSubstructMatch(patt['lactone']) or row['n_aromatic_rings']==0) and nO>=3: base='polyketide'
    elif row['n_aromatic_rings']>=1 and len(m.GetSubstructMatches(patt['phenol']))>=2: base='polyphenol/phenolic'
    elif nN==0 and row['n_rings']<=1: base='fatty-acid/linear lipid'
    elif nS>=1: base='sulfur-containing'
    else: base='other/mixed'
    tags=[base]
    if row['is_macrocycle']: tags.append('macrocyclic')
    if hal: tags.append('halogenated')
    return ";".join(tags)

