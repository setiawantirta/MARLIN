def pubchem_title(ik, attempts=4):
    """Common name for an InChIKey, or None.

    A transient network failure must never leak an error string into a panel
    label, so the lookup retries with exponential backoff and then returns
    None; the caller falls back to the CMNPD identifier.
    """
    url=f"https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/inchikey/{ik}/property/Title,CanonicalSMILES/JSON"
    for k in range(attempts):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:
                d=_json.load(r)
            p=d['PropertyTable']['Properties'][0]
            return p.get('Title'), p.get('CID')
        except urllib.error.HTTPError as e:
            if e.code==404:
                return (None, None)
            time.sleep(1.5*(k+1))
        except Exception:
            time.sleep(1.5*(k+1))
    return (None, None)

