_COMPARATOR = ["#1f77b4", "#ff7f0e", "#9467bd", "#8c564b", "#17becf", "#7f7f7f", "#bcbd22"]


def _colors(focal):
    others = [a for a in ORDER if a != focal]
    cmap = {a: _COMPARATOR[i % len(_COMPARATOR)] for i, a in enumerate(others)}
    cmap[focal] = "#c0392b"
    return cmap


