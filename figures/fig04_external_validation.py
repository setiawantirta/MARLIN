def cmnpd_matrix(path, n):
    z2 = np.load(path)
    P = np.full((n, len(TASKS)), np.nan, np.float64)
    P[z2["I"]] = z2["P"]
    return P

def seed_mean(paths, n):
    Ps = [cmnpd_matrix(p, n) for p in paths]
    return np.nanmean(np.stack(Ps), axis=0)

